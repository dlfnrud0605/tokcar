-- TokCar 1단계 스키마 (ERD v1.1). H2(PostgreSQL 모드)와 PostgreSQL 둘 다에서 돈다.
-- 2단계 테이블(phone_verifications, devices)은 그때 V2로 더한다.

CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id          VARCHAR(20)  NOT NULL UNIQUE,
    password_hash     VARCHAR(100) NOT NULL,
    phone_e164        VARCHAR(16)  NOT NULL UNIQUE,
    country           VARCHAR(2)   NOT NULL,
    name              VARCHAR(20)  NOT NULL,
    status_msg        VARCHAR(60),
    profile_image_key VARCHAR(200),
    failed_logins     INT          NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE friendships (
    user_id    BIGINT NOT NULL REFERENCES users (id),
    friend_id  BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, friend_id)
);

CREATE TABLE rooms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(30) NOT NULL,
    created_by  BIGINT      NOT NULL REFERENCES users (id),
    last_msg_id BIGINT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE room_members (
    room_id          BIGINT NOT NULL REFERENCES rooms (id),
    user_id          BIGINT NOT NULL REFERENCES users (id),
    last_read_msg_id BIGINT NOT NULL DEFAULT 0,
    joined_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (room_id, user_id)
);
CREATE INDEX idx_room_members_user ON room_members (user_id);

CREATE TABLE room_places (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT           NOT NULL REFERENCES rooms (id),
    name    VARCHAR(60)      NOT NULL,
    addr    VARCHAR(120)     NOT NULL,
    lat     DOUBLE PRECISION NOT NULL,
    lon     DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_room_places UNIQUE (room_id, name, addr)
);
CREATE INDEX idx_room_places_room ON room_places (room_id, id);

CREATE TABLE messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT      NOT NULL REFERENCES rooms (id),
    sender_id  BIGINT REFERENCES users (id),
    kind       VARCHAR(10) NOT NULL,
    text       VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_messages_room ON messages (room_id, id);
CREATE INDEX idx_messages_created ON messages (created_at);

CREATE TABLE message_locations (
    message_id BIGINT PRIMARY KEY REFERENCES messages (id),
    place_name VARCHAR(60)      NOT NULL,
    place_addr VARCHAR(120)     NOT NULL,
    lat        DOUBLE PRECISION NOT NULL,
    lon        DOUBLE PRECISION NOT NULL
);

CREATE TABLE route_shares (
    message_id BIGINT PRIMARY KEY REFERENCES messages (id),
    state      VARCHAR(8)       NOT NULL,
    from_addr  VARCHAR(120)     NOT NULL,
    from_lat   DOUBLE PRECISION NOT NULL,
    from_lon   DOUBLE PRECISION NOT NULL,
    dest_name  VARCHAR(60)      NOT NULL,
    dest_addr  VARCHAR(120)     NOT NULL,
    dest_lat   DOUBLE PRECISION NOT NULL,
    dest_lon   DOUBLE PRECISION NOT NULL,
    ended_at   TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_route_shares_state ON route_shares (state);
